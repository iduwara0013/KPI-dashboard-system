async function actor(browser, email, ui = false) {
  const context = await browser.newContext({ baseURL: 'http://127.0.0.1:5174', viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  if (ui) {
    await page.goto('/');
    await page.getByLabel(/^Email address/).fill(email);
    await page.getByLabel(/^Password/).fill(password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible();
  } else {
    const session = await (await context.request.get('/api/session')).json();
    const result = await context.request.post('/api/login', { headers: { 'X-CSRF-TOKEN': session.csrf_token }, data: { email, password } });
    expect(result.ok(), await result.text()).toBeTruthy();
  }
  return { context, page };
}
async function mutate(context, url, data, method = 'post') {
  const session = await (await context.request.get('/api/session')).json();
  const response = await context.request[method](url, { headers: { 'X-CSRF-TOKEN': session.csrf_token, 'X-Workspace-User': String(session.user.id) }, data });
  expect(response.ok(), await response.text()).toBeTruthy();
  return response.json();
}
async function workspace(context, area = 'delivery') {
  const response = await context.request.get(`/api/${area}/workspace`);
  expect(response.ok(), await response.text()).toBeTruthy();
  return response.json();
}

